def paper_position(idx, total):
    """Normalized position 0-1 within paper."""
    return round((idx + 1) / total, 3)


def emit_rows(paper_id, items):
    n = len(items)
    for i, it in enumerate(items):
        qid, rate, con, rea, nov, vis, mod, opn, topic, scene, pattern = it
        yield {
            "question_id": qid,
            "paper_id": paper_id,
            "score_rate": rate,
            "concept": con,
            "reasoning": rea,
            "novelty": nov,
            "visual": vis,
            "modeling": mod,
            "position": paper_position(i, n),
            "is_open": opn,
            "topic_mech": 1 if topic == "mech" else 0,
            "topic_em": 1 if topic == "em" else 0,
            "topic_thermo_optics_modern": 1 if topic == "toam" else 0,
            "textbook_scene_degree": scene,
            "textbook_pattern_degree": pattern,
        }


def main():
    FIELDS = [
        "question_id", "paper_id", "score_rate",
        "concept", "reasoning", "novelty", "visual", "modeling",
        "position", "is_open",
        "topic_mech", "topic_em", "topic_thermo_optics_modern",
        "textbook_scene_degree", "textbook_pattern_degree",
    ]
    rows = []
    rows.extend(emit_rows("xicheng_2024", XICHENG_2024))
    rows.extend(emit_rows("xicheng_2025", XICHENG_2025))
    rows.extend(emit_rows("xicheng_2026", XICHENG_2026))
    rows.extend(emit_rows("gaokao_2024",  GAOKAO_2024))
    rows.extend(emit_rows("gaokao_2025",  GAOKAO_2025))

    OUT_CSV.parent.mkdir(parents=True, exist_ok=True)
    with OUT_CSV.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS)
        w.writeheader()
        for r in rows:
            w.writerow(r)

    print(f"wrote {len(rows)} rows to {OUT_CSV.relative_to(REPO_ROOT)}")
