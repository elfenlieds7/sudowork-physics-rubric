def main():
    with open(SRC, encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    fields = list(rows[0].keys())

    v23_rows = []
    missing = []
    for r in rows:
        key = (r["paper_id"], r["question_id"])
        if key not in V23:
            missing.append(key)
            v23_rows.append(dict(r))
            continue
        new_count, _ = V23[key]
        r2 = dict(r)
        r2["concept_count"] = str(new_count)
        v23_rows.append(r2)

    print(f"Total rows: {len(rows)}")
    print(f"Relabeled: {len(rows) - len(missing)}")
    print(f"Missing labels: {len(missing)}")
    if missing:
        for k in missing:
            print(f"  {k}")

    with open(OUT_CSV, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(v23_rows)

    reasoning = {f"{k[0]}::{k[1]}": {"count": c, "reasoning": r}
                 for k, (c, r) in V23.items()}
    with open(OUT_JSON, "w", encoding="utf-8") as f:
        json.dump(reasoning, f, ensure_ascii=False, indent=2)

    # Distribution
    from collections import Counter
    dist_old = Counter(r["concept_count"] for r in rows)
    dist_new = Counter(r["concept_count"] for r in v23_rows)
    print(f"\nDistribution v2.2: {dict(sorted(dist_old.items()))}")
    print(f"Distribution v2.3: {dict(sorted(dist_new.items()))}")

    print(f"\nWrote {OUT_CSV}")
    print(f"Wrote {OUT_JSON}")


if __name__ == "__main__":
    main()
